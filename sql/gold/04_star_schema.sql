-- 4.5 Populate DIM_PAYMENT
-- Insert standard default unknown row
INSERT INTO gold.dim_payment (
    payment_key,
    payment_type,
    payment_installments,
    payment_installments_range
)
OVERRIDING SYSTEM VALUE
VALUES (0, 'UNKNOWN', 1, 'Not Applicable');

-- Insert distinct combinations from silver.payments
INSERT INTO gold.dim_payment (
    payment_type,
    payment_installments,
    payment_installments_range
)
SELECT
    payment_type,
    payment_installments,
    CASE
        WHEN payment_installments = 1 THEN '1 Installment'
        WHEN payment_installments BETWEEN 2 AND 3 THEN '2-3 Installments'
        WHEN payment_installments BETWEEN 4 AND 6 THEN '4-6 Installments'
        WHEN payment_installments >= 7 THEN '7+ Installments'
        ELSE '1 Installment'
    END AS payment_installments_range
FROM (
    SELECT DISTINCT
        COALESCE(payment_type, 'UNKNOWN') AS payment_type,
        GREATEST(1, COALESCE(payment_installments, 1)) AS payment_installments
    FROM silver.payments
) p
ON CONFLICT (payment_type, payment_installments) DO NOTHING;

-- -----------------------------------------------------------------------------
-- 5. POPULATE FACT TABLE (FACT_SALES)
-- -----------------------------------------------------------------------------
WITH primary_order_payment AS (
    SELECT DISTINCT ON (order_id)
        order_id,
        COALESCE(payment_type, 'UNKNOWN') AS payment_type,
        GREATEST(1, COALESCE(payment_installments, 1)) AS payment_installments
    FROM silver.payments
    ORDER BY order_id, payment_value DESC, payment_sequential ASC
)
INSERT INTO gold.fact_sales (
    order_id,
    order_item_id,
    customer_key,
    product_key,
    seller_key,
    date_key,
    payment_key,
    order_status,
    purchase_timestamp,
    shipping_limit_date,
    price,
    freight_value,
    total_amount,
    quantity,
    estimated_cost,
    estimated_profit
)
SELECT
    f.order_id,
    f.order_item_id,
    c.customer_key,
    p.product_key,
    s.seller_key,
    TO_CHAR(f.purchase_timestamp, 'YYYYMMDD')::INTEGER AS date_key,
    COALESCE(pay.payment_key, 0) AS payment_key,
    f.order_status,
    f.purchase_timestamp,
    f.shipping_limit_date,
    f.price,
    f.freight_value,
    ROUND(f.price + f.freight_value, 2) AS total_amount,
    1 AS quantity,
    ROUND((f.price * 0.70) + (f.freight_value * 0.15), 2) AS estimated_cost,
    ROUND((f.price * 0.30) - (f.freight_value * 0.15), 2) AS estimated_profit
FROM silver.order_fact f
JOIN gold.dim_customer c ON f.customer_id = c.customer_id
JOIN gold.dim_product p ON f.product_id = p.product_id
JOIN gold.dim_seller s ON f.seller_id = s.seller_id
LEFT JOIN primary_order_payment pop ON f.order_id = pop.order_id
LEFT JOIN gold.dim_payment pay ON pop.payment_type = pay.payment_type AND pop.payment_installments = pay.payment_installments;
