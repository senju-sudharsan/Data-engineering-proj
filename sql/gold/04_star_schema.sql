-- =============================================================================
-- GOLD LAYER: DIMENSIONAL STAR SCHEMA (OLAP)
-- =============================================================================
-- Target Schema: gold
-- Tables:
--   1. gold.dim_date
--   2. gold.dim_customer
--   3. gold.dim_product
--   4. gold.dim_seller
--   5. gold.dim_payment
--   6. gold.fact_sales
--
-- Notes on Metrics:
--   estimated_cost and estimated_profit are modeled proxy metrics:
--   - Estimated Product Cost = Price * 70% (30% benchmark gross product margin)
--   - Freight Handling Overhead = Freight Value * 15%
--   - Estimated Profit = Price - Estimated Product Cost - Freight Handling Overhead
--                      = (Price * 0.30) - (Freight Value * 0.15)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. DROP EXISTING STAR SCHEMA OBJECTS (Preserving legacy summary tables)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS gold.fact_sales CASCADE;
DROP TABLE IF EXISTS gold.dim_payment CASCADE;
DROP TABLE IF EXISTS gold.dim_seller CASCADE;
DROP TABLE IF EXISTS gold.dim_product CASCADE;
DROP TABLE IF EXISTS gold.dim_customer CASCADE;
DROP TABLE IF EXISTS gold.dim_date CASCADE;

-- -----------------------------------------------------------------------------
-- 2. CREATE DIMENSION TABLES
-- -----------------------------------------------------------------------------

-- 2.1 DIM_DATE
CREATE TABLE gold.dim_date (
    date_key INTEGER PRIMARY KEY, -- YYYYMMDD
    full_date DATE NOT NULL UNIQUE,
    year INTEGER NOT NULL,
    quarter INTEGER NOT NULL,
    quarter_name VARCHAR(10) NOT NULL,
    month INTEGER NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    month_short VARCHAR(5) NOT NULL,
    day INTEGER NOT NULL,
    day_of_week INTEGER NOT NULL,
    day_name VARCHAR(20) NOT NULL,
    is_weekend BOOLEAN NOT NULL,
    year_month VARCHAR(7) NOT NULL,
    year_quarter VARCHAR(10) NOT NULL
);

CREATE INDEX idx_dim_date_year_month ON gold.dim_date (year, month);

-- 2.2 DIM_CUSTOMER
CREATE TABLE gold.dim_customer (
    customer_key BIGSERIAL PRIMARY KEY,
    customer_id VARCHAR(50) NOT NULL UNIQUE,
    customer_unique_id VARCHAR(50),
    customer_zip_code_prefix VARCHAR(20),
    customer_city VARCHAR(100),
    customer_state VARCHAR(10),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dim_customer_state ON gold.dim_customer (customer_state);
CREATE INDEX idx_dim_customer_city ON gold.dim_customer (customer_city);

-- 2.3 DIM_PRODUCT
CREATE TABLE gold.dim_product (
    product_key BIGSERIAL PRIMARY KEY,
    product_id VARCHAR(50) NOT NULL UNIQUE,
    product_category_name VARCHAR(100),
    product_category_name_english VARCHAR(100),
    product_name_length INTEGER,
    product_description_length INTEGER,
    product_photos_qty INTEGER,
    product_weight_g NUMERIC,
    product_length_cm NUMERIC,
    product_height_cm NUMERIC,
    product_width_cm NUMERIC,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dim_product_category ON gold.dim_product (product_category_name_english);

-- 2.4 DIM_SELLER
CREATE TABLE gold.dim_seller (
    seller_key BIGSERIAL PRIMARY KEY,
    seller_id VARCHAR(50) NOT NULL UNIQUE,
    seller_zip_code_prefix VARCHAR(20),
    seller_city VARCHAR(100),
    seller_state VARCHAR(10),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dim_seller_state ON gold.dim_seller (seller_state);

-- 2.5 DIM_PAYMENT
CREATE TABLE gold.dim_payment (
    payment_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type VARCHAR(50) NOT NULL,
    payment_installments INTEGER NOT NULL DEFAULT 1,
    payment_installments_range VARCHAR(50) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payment_profile UNIQUE (payment_type, payment_installments)
);

-- -----------------------------------------------------------------------------
-- 3. CREATE FACT TABLE
-- -----------------------------------------------------------------------------
CREATE TABLE gold.fact_sales (
    sales_key BIGSERIAL PRIMARY KEY,
    order_id VARCHAR(50) NOT NULL,
    order_item_id INTEGER NOT NULL,
    customer_key BIGINT NOT NULL REFERENCES gold.dim_customer(customer_key),
    product_key BIGINT NOT NULL REFERENCES gold.dim_product(product_key),
    seller_key BIGINT NOT NULL REFERENCES gold.dim_seller(seller_key),
    date_key INTEGER NOT NULL REFERENCES gold.dim_date(date_key),
    payment_key BIGINT NOT NULL REFERENCES gold.dim_payment(payment_key),
    order_status VARCHAR(50),
    purchase_timestamp TIMESTAMP NOT NULL,
    shipping_limit_date TIMESTAMP,
    price NUMERIC(18,2) NOT NULL,
    freight_value NUMERIC(18,2) NOT NULL,
    total_amount NUMERIC(18,2) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    estimated_cost NUMERIC(18,2) NOT NULL,
    estimated_profit NUMERIC(18,2) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fact_sales_item UNIQUE (order_id, order_item_id)
);

CREATE INDEX idx_fact_sales_date ON gold.fact_sales (date_key);
CREATE INDEX idx_fact_sales_customer ON gold.fact_sales (customer_key);
CREATE INDEX idx_fact_sales_product ON gold.fact_sales (product_key);
CREATE INDEX idx_fact_sales_seller ON gold.fact_sales (seller_key);
CREATE INDEX idx_fact_sales_payment ON gold.fact_sales (payment_key);
CREATE INDEX idx_fact_sales_order_status ON gold.fact_sales (order_status);

-- -----------------------------------------------------------------------------
-- 4. POPULATE DIMENSIONS FROM SILVER
-- -----------------------------------------------------------------------------

-- 4.1 Populate DIM_DATE (2016-01-01 to 2019-12-31)
INSERT INTO gold.dim_date (
    date_key,
    full_date,
    year,
    quarter,
    quarter_name,
    month,
    month_name,
    month_short,
    day,
    day_of_week,
    day_name,
    is_weekend,
    year_month,
    year_quarter
)
SELECT
    TO_CHAR(d, 'YYYYMMDD')::INTEGER AS date_key,
    d::DATE AS full_date,
    EXTRACT(YEAR FROM d)::INTEGER AS year,
    EXTRACT(QUARTER FROM d)::INTEGER AS quarter,
    'Q' || EXTRACT(QUARTER FROM d)::TEXT AS quarter_name,
    EXTRACT(MONTH FROM d)::INTEGER AS month,
    RTRIM(TO_CHAR(d, 'Month')) AS month_name,
    TO_CHAR(d, 'Mon') AS month_short,
    EXTRACT(DAY FROM d)::INTEGER AS day,
    EXTRACT(ISODOW FROM d)::INTEGER AS day_of_week,
    RTRIM(TO_CHAR(d, 'Day')) AS day_name,
    CASE WHEN EXTRACT(ISODOW FROM d) IN (6, 7) THEN TRUE ELSE FALSE END AS is_weekend,
    TO_CHAR(d, 'YYYY-MM') AS year_month,
    TO_CHAR(d, 'YYYY') || '-Q' || EXTRACT(QUARTER FROM d)::TEXT AS year_quarter
FROM GENERATE_SERIES('2016-01-01'::DATE, '2019-12-31'::DATE, '1 day'::INTERVAL) d;

-- 4.2 Populate DIM_CUSTOMER
INSERT INTO gold.dim_customer (
    customer_id,
    customer_unique_id,
    customer_zip_code_prefix,
    customer_city,
