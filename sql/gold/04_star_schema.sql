-- 4.3 Populate DIM_PRODUCT (With English translations from bronze.category_translation_raw)
INSERT INTO gold.dim_product (
    product_id,
    product_category_name,
    product_category_name_english,
    product_name_length,
    product_description_length,
    product_photos_qty,
    product_weight_g,
    product_length_cm,
    product_height_cm,
    product_width_cm
)
SELECT
    p.product_id,
    p.product_category_name,
    INITCAP(REPLACE(COALESCE(t.product_category_name_english, p.product_category_name, 'Other'), '_', ' ')) AS product_category_name_english,
    p.product_name_length,
    p.product_description_length,
    p.product_photos_qty,
    p.product_weight_g,
    p.product_length_cm,
    p.product_height_cm,
    p.product_width_cm
FROM silver.products p
LEFT JOIN (
    SELECT DISTINCT
        LOWER(product_category_name) AS product_category_name,
        product_category_name_english
    FROM bronze.category_translation_raw
) t ON LOWER(p.product_category_name) = t.product_category_name
ORDER BY p.product_id;

